class PlanComplexity(str, Enum):
    """Estimated computational and analytical complexity of an execution plan."""

    LOW = "LOW"          # 1-2 independent tasks, linear execution
    MEDIUM = "MEDIUM"    # 3-5 tasks, 2-3 parallel execution stages
    HIGH = "HIGH"        # 6+ tasks, multi-agent cross-dependency graphs
    CRITICAL = "CRITICAL"  # Deep multi-hop graph exploration with extensive verification


@dataclass
class PlannedTask:
    """Specification of an individual atomic subtask within an ExecutionPlan.

    Attributes:
        task_id: Unique string identifier for the subtask.
        name: Short human-readable title.
        agent_role: Specialized agent responsible for execution
                    ('researcher', 'quant', 'critic', 'synthesizer').
        description: Detailed instructions and prompt context for the agent.
        dependencies: Task IDs that must finish before this task can execute.
        input_context: Arbitrary payload or variables required by the task.
        expected_output: Description of what the task must produce.
    """

    task_id: str
    name: str
    agent_role: str
    description: str
    dependencies: List[str] = field(default_factory=list)
    input_context: Dict[str, Any] = field(default_factory=dict)
    expected_output: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return {
            "task_id": self.task_id,
            "name": self.name,
            "agent_role": self.agent_role,
            "description": self.description,
            "dependencies": self.dependencies,
            "input_context": self.input_context,
            "expected_output": self.expected_output,
        }


@dataclass
class ExecutionPlan:
    """Complete multi-agent execution plan governed by a Directed Acyclic Graph (DAG).

    Attributes:
        plan_id: Unique identifier for the plan.
        query: Original user query or intelligence directive.
        tasks: Mapping of task_id to PlannedTask instances.
        dag: Underlying DAG managing dependencies and cycle invariants.
        batches: Parallel execution stages generated by Kahn's Algorithm.
        topological_order: Flattened linear ordering of all task IDs.
        complexity: Estimated complexity rating.
        created_at: Epoch timestamp of plan creation.
        metadata: Additional telemetry or intent analysis data.
    """

    plan_id: str
    query: str
    tasks: Dict[str, PlannedTask]
    dag: DAG
    batches: List[List[str]]
    topological_order: List[str]
    complexity: PlanComplexity = PlanComplexity.MEDIUM
    created_at: float = field(default_factory=time.time)
    metadata: Dict[str, Any] = field(default_factory=dict)

    @property
    def total_tasks(self) -> int:
        """Total number of scheduled tasks."""
        return len(self.tasks)

    @property
    def total_stages(self) -> int:
        """Number of sequential execution stages (critical path length)."""
        return len(self.batches)

    @property
    def max_parallel_width(self) -> int:
        """Maximum number of tasks executable concurrently in any single stage."""
        return max((len(b) for b in self.batches), default=0)

    def get_stage_for_task(self, task_id: str) -> int:
        """Find the zero-indexed execution batch index containing task_id."""
        for idx, batch in enumerate(self.batches):
            if task_id in batch:
                return idx
        raise KeyError(f"Task '{task_id}' not found in any execution batch.")

    def summary(self) -> str:
        """Format a human-readable execution roadmap for logging and debugging."""
        lines = [
            f"=== Execution Plan [{self.plan_id}] ===",
            f"Query: {self.query}",
            f"Complexity: {self.complexity.value} | Total Tasks: {self.total_tasks} | Stages: {self.total_stages} | Max Concurrency: {self.max_parallel_width}",
            "-" * 60,
        ]
        for stage_idx, batch in enumerate(self.batches):
            lines.append(f"Stage {stage_idx + 1} (Parallel Execution):")
            for t_id in batch:
                task = self.tasks[t_id]
                deps = f" [Prerequisites: {', '.join(task.dependencies)}]" if task.dependencies else " [Root: No Prerequisites]"
                lines.append(f"  • [{task.agent_role.upper()}] {task.task_id}: {task.name}{deps}")
        lines.append("=" * 60)
        return "\n".join(lines)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "plan_id": self.plan_id,
            "query": self.query,
            "complexity": self.complexity.value,
            "total_tasks": self.total_tasks,
            "total_stages": self.total_stages,
            "max_parallel_width": self.max_parallel_width,
            "batches": self.batches,
            "topological_order": self.topological_order,
            "tasks": {t_id: t.to_dict() for t_id, t in self.tasks.items()},
            "created_at": self.created_at,
            "metadata": self.metadata,
        }


class PlannerAgent(BaseAgent):
    """Autonomous Planning Agent responsible for multi-step query decomposition.

    Analyzes complex user directives, identifies required agent roles, models
    dependencies in a Directed Acyclic Graph, and computes parallel execution
    stages using Kahn's algorithm.
    """

    def __init__(
        self,
        agent_id: str = "planner",
        name: str = "Planner Agent",
        event_bus: Optional[EventBus] = None,
        memory_capacity: int = 50,
        llm_callable: Optional[Callable[[str], str]] = None,
    ) -> None:
        super().__init__(
            agent_id=agent_id,
            name=name,
            role="Strategic Query Decomposition & Multi-Agent DAG Planning",
            goal="Decompose complex intelligence requests into parallelized, acyclic execution graphs",
            tools=[],
            event_bus=event_bus,
            memory_capacity=memory_capacity,
        )
        self.llm_callable = llm_callable
        self._plan_counter: int = 0

    # -------------------------------------------------------------------------
    # Core Plan Generation & Decomposition
    # -------------------------------------------------------------------------

    def create_plan(
        self,
        query: str,
        context: Optional[Dict[str, Any]] = None,
    ) -> ExecutionPlan:
        """Decompose a query into a validated, parallelized ExecutionPlan.

        Args:
            query: The high-level user question or directive.
            context: Optional prior conversation or domain context.

        Returns:
            ExecutionPlan with validated DAG and Kahn's algorithm batches.

        Raises:
            ValueError: If query is empty or cannot be decomposed.
            CyclicDependencyError: If a cyclic loop is detected.
        """
        clean_query = query.strip()
        if not clean_query:
            raise ValueError("Query string cannot be empty.")

        self._plan_counter += 1
        plan_id = f"plan_{int(time.time())}_{self._plan_counter}"

        # 1. Analyze query intent and extract key entities/sub-aspects
        intent = self._analyze_intent(clean_query, context=context)

        # 2. Generate PlannedTask items based on intent analysis
        tasks = self._synthesize_tasks(clean_query, intent)

        # 3. Construct and validate the DAG
        dag = DAG()
        for task in tasks:
            dag.add_task(
                task_id=task.task_id,
                name=task.name,
                dependencies=task.dependencies,
            )

        # 4. Resolve Kahn's algorithm topological order & parallel execution batches
        topological_order = dag.topological_sort()
        batches = dag.get_execution_batches()

        # 5. Determine plan complexity
        complexity = self._calculate_complexity(tasks, batches)

        plan = ExecutionPlan(
            plan_id=plan_id,
            query=clean_query,
            tasks={t.task_id: t for t in tasks},
            dag=dag,
            batches=batches,
            topological_order=topological_order,
            complexity=complexity,
            metadata={"intent": intent, "context": context or {}},
        )

        return plan

    def replan(
        self,
        original_plan: ExecutionPlan,
        failed_task_id: str,
        feedback: str,
    ) -> ExecutionPlan:
        """Dynamically generate a revised execution plan to recover from a failure or rejection.

        Inserts a targeted remediation task and rewires downstream dependencies.

        Args:
            original_plan: The prior ExecutionPlan that encountered a failure.
            failed_task_id: The ID of the task that failed or was rejected by Critic.
            feedback: Error message or critique explaining the failure.

        Returns:
            New ExecutionPlan containing the remediation pathway.
        """
        if failed_task_id not in original_plan.tasks:
            raise KeyError(f"Task '{failed_task_id}' not found in original plan.")

        failed_task = original_plan.tasks[failed_task_id]
        remediation_task_id = f"remedy_{failed_task_id}"

        # Create remediation task with higher precision / alternative strategy
        remediation_task = PlannedTask(
            task_id=remediation_task_id,
            name=f"Remediate: {failed_task.name}",
            agent_role=failed_task.agent_role,
            description=(
                f"Address previous failure in '{failed_task.name}'. "
                f"Critic/Error Feedback: {feedback}. Original task: {failed_task.description}"
            ),
            dependencies=list(failed_task.dependencies),
            input_context={
                "failed_task_id": failed_task_id,
                "feedback": feedback,
                **failed_task.input_context,
            },
            expected_output=f"Corrected and verified output addressing: {feedback}",
        )

        # Build new task map
        new_tasks: Dict[str, PlannedTask] = {}
        for t_id, task in original_plan.tasks.items():
            if t_id == failed_task_id:
                new_tasks[remediation_task_id] = remediation_task
            else:
                # If downstream task depended on failed_task_id, rewire to remediation_task_id
                updated_deps = [
                    remediation_task_id if dep == failed_task_id else dep
                    for dep in task.dependencies
                ]
                updated_task = PlannedTask(
                    task_id=task.task_id,
                    name=task.name,
                    agent_role=task.agent_role,
                    description=task.description,
                    dependencies=updated_deps,
                    input_context=task.input_context,
                    expected_output=task.expected_output,
                )
                new_tasks[t_id] = updated_task

        # Construct new DAG
        dag = DAG()
        for task in new_tasks.values():
            dag.add_task(
                task_id=task.task_id,
                name=task.name,
                dependencies=task.dependencies,
            )

        topological_order = dag.topological_sort()
        batches = dag.get_execution_batches()
        complexity = self._calculate_complexity(list(new_tasks.values()), batches)

        self._plan_counter += 1
        new_plan_id = f"replan_{int(time.time())}_{self._plan_counter}"

        return ExecutionPlan(
            plan_id=new_plan_id,
            query=original_plan.query,
            tasks=new_tasks,
            dag=dag,
            batches=batches,
            topological_order=topological_order,
            complexity=complexity,
            metadata={
                "parent_plan_id": original_plan.plan_id,
                "remediated_task_id": failed_task_id,
                "feedback": feedback,
            },
        )

    # -------------------------------------------------------------------------
    # Intent Analysis & Task Decomposition Heuristics
    # -------------------------------------------------------------------------

    def _analyze_intent(self, query: str, context: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
        """Classify analytical dimensions required by the user prompt."""
        q_lower = query.lower()

        # Domain signals
        has_quant = any(
            kw in q_lower
            for kw in [
                "ratio", "margin", "revenue", "ebitda", "pe ratio", "p/e",
                "debt", "valuation", "cagr", "financial", "growth rate",
                "balance sheet", "cash flow", "roe", "roa", "percentage",
                "metric", "forecast", "multiple", "discounted cash flow", "dcf"
            ]
        )

        has_research = any(
            kw in q_lower
            for kw in [
                "moat", "competitive", "strategy", "supplier", "supply chain",
                "risk", "geopolitical", "market share", "leadership", "executive",
                "patent", "technology", "architecture", "customer", "acquisition",
                "overview", "profile", "investigation", "analysis", "competitor"
            ]
        ) or not has_quant  # Default to research if no explicit quant signals

        has_critic = any(
            kw in q_lower
            for kw in [
                "verify", "audit", "critique", "validate", "stress test",
                "fact-check", "discrepancy", "hallucination", "accuracy",
                "reconcile", "cross-examine", "comprehensive"
            ]
        ) or len(query.split()) > 15  # Comprehensive queries always require a verification phase

        # Entity extraction (rule-based keywords or capitalization)
        detected_entities = self._extract_candidate_entities(query)

        return {
            "has_research": has_research,
            "has_quant": has_quant,
            "has_critic": has_critic,
            "entities": detected_entities,
            "is_comparison": " vs " in q_lower or "versus" in q_lower or "compare" in q_lower,
        }

    def _extract_candidate_entities(self, query: str) -> List[str]:
        """Extract candidate company or domain entities using capitalized token groups."""
        # Find proper nouns or known patterns
        candidates: List[str] = []
        words = query.replace("?", " ").replace("!", " ").replace(",", " ").split()
        for w in words:
            clean = re.sub(r"[^\w]", "", w)
            if clean and clean[0].isupper() and clean.lower() not in {
                "what", "how", "why", "when", "where", "evaluate", "analyze",
                "compare", "calculate", "assess", "is", "the", "and", "or",
                "for", "in", "of", "to", "a", "an", "on", "with"
            }:
                if clean not in candidates:
                    candidates.append(clean)
        return candidates

    def _synthesize_tasks(self, query: str, intent: Dict[str, Any]) -> List[PlannedTask]:
        """Decompose analyzed intent into concrete PlannedTask specifications."""
        tasks: List[PlannedTask] = []
        entities = intent.get("entities", [])
        primary_subject = entities[0] if entities else "Target Subject"

        # ---------------------------------------------------------------------
        # Stage 1: Root Ingestion & Information Gathering Tasks (Parallel Batch 0)
        # ---------------------------------------------------------------------
        research_tasks: List[str] = []
        quant_tasks: List[str] = []

        if intent.get("has_research"):
            if intent.get("is_comparison") and len(entities) >= 2:
                # Comparative multi-entity branch
                for ent in entities[:2]:
                    task_id = f"research_{ent.lower()}_profile"
                    tasks.append(
                        PlannedTask(
                            task_id=task_id,
                            name=f"Qualitative Research: {ent}",
                            agent_role="researcher",
                            description=f"Gather market position, business model, competitive moat, and strategic risks for {ent}.",
                            dependencies=[],
                            input_context={"entity": ent, "query": query},
                            expected_output=f"Comprehensive qualitative dossier for {ent}.",
                        )
                    )
                    research_tasks.append(task_id)
            else:
                task_id = f"research_{primary_subject.lower()}_core"
                tasks.append(
                    PlannedTask(
                        task_id=task_id,
                        name=f"Qualitative Research: {primary_subject}",
                        agent_role="researcher",
                        description=f"Retrieve factual evidence, competitive dynamics, industry drivers, and operational risks concerning {query}.",
                        dependencies=[],
                        input_context={"subject": primary_subject, "query": query},
                        expected_output=f"Detailed factual research synthesis on {primary_subject}.",
                    )
                )
                research_tasks.append(task_id)

        if intent.get("has_quant"):
            if intent.get("is_comparison") and len(entities) >= 2:
                task_id = "quant_comparative_metrics"
                tasks.append(
                    PlannedTask(
                        task_id=task_id,
                        name=f"Quantitative Analysis: {', '.join(entities[:2])}",
                        agent_role="quant",
                        description=f"Extract and compute comparative financial metrics, operating margins, and valuation multiples for {', '.join(entities[:2])}.",
                        dependencies=[],
                        input_context={"entities": entities[:2], "query": query},
                        expected_output=f"Comparative financial model for {', '.join(entities[:2])}.",
                    )
                )
                quant_tasks.append(task_id)
            else:
                task_id = f"quant_{primary_subject.lower()}_metrics"
                tasks.append(
                    PlannedTask(
                        task_id=task_id,
                        name=f"Quantitative Analysis: {primary_subject}",
                        agent_role="quant",
                        description=f"Extract and compute financial metrics, operating margins, valuation multiples, and statistical trends relevant to: {query}.",
                        dependencies=[],
                        input_context={"subject": primary_subject, "query": query},
                        expected_output="Computed financial metrics, valuation tables, and statistical ratios.",
                    )
                )
                quant_tasks.append(task_id)

        # ---------------------------------------------------------------------
        # Stage 2: Cross-Functional Integration & Critical Reflection
        # ---------------------------------------------------------------------
        upstream_evidence_tasks = research_tasks + quant_tasks

        # Critic verification task
        critic_task_id = "critic_fact_verification"
        tasks.append(
            PlannedTask(
                task_id=critic_task_id,
                name="Fact Verification & Stress Testing",
                agent_role="critic",
                description=(
                    "Audit research findings and quantitative outputs for factual hallucinations, "
                    "inconsistent numerical claims, and ungrounded assumptions."
                ),
                dependencies=list(upstream_evidence_tasks),
                input_context={"evidence_task_ids": upstream_evidence_tasks},
                expected_output="Verification audit report confirming factual accuracy or flagging discrepancies.",
            )
        )

        # ---------------------------------------------------------------------
        # Stage 3: Executive Synthesis & Final Intelligence Dossier (Terminal Leaf)
        # ---------------------------------------------------------------------
        synthesis_task_id = "synthesizer_final_dossier"
        all_prior_tasks = upstream_evidence_tasks + [critic_task_id]
        tasks.append(
            PlannedTask(
                task_id=synthesis_task_id,
                name="Executive Intelligence Synthesis",
                agent_role="synthesizer",
                description=(
                    f"Consolidate verified qualitative evidence and quantitative models into an "
                    f"executive intelligence report addressing the primary query: '{query}'."
                ),
                dependencies=all_prior_tasks,
                input_context={"query": query, "verified_by": critic_task_id},
                expected_output="Structured, publication-ready intelligence briefing with executive takeaways.",
            )
        )

        return tasks

    def _calculate_complexity(
        self,
        tasks: List[PlannedTask],
        batches: List[List[str]],
    ) -> PlanComplexity:
        """Assign plan complexity grade based on node count and critical path depth."""
        n_tasks = len(tasks)
        n_stages = len(batches)

        if n_tasks <= 2 and n_stages <= 2:
            return PlanComplexity.LOW
        elif n_tasks <= 4 and n_stages <= 3:
            return PlanComplexity.MEDIUM
        elif n_tasks <= 7:
            return PlanComplexity.HIGH
        else:
            return PlanComplexity.CRITICAL

    # -------------------------------------------------------------------------
    # BaseAgent Cognitive Implementation: think() and reflect()
    # -------------------------------------------------------------------------

    async def think(self, task: str, context: Optional[Dict[str, Any]] = None) -> str:
        """Formulate execution plan and serialize DAG topology into working memory."""
        plan = self.create_plan(task, context=context)

        # Cache active plan in working scratchpad
        self.memory.set_variable("active_plan", plan)
        self.memory.set_variable("active_plan_id", plan.plan_id)

        # Broadcast plan generation event
        await self._emit_event(
            EventType.TASK_SCHEDULED,
            {
                "plan_id": plan.plan_id,
                "total_tasks": plan.total_tasks,
                "stages": plan.total_stages,
                "complexity": plan.complexity.value,
            },
        )

        return plan.summary()

    async def reflect(
        self,
        task: str,
        thoughts: str,
        execution_log: List[Dict[str, Any]],
    ) -> Tuple[bool, str]:
        """Self-verify that the generated plan is acyclic, executable, and complete."""
        plan: Optional[ExecutionPlan] = self.memory.get_variable("active_plan")
        if plan is None:
            return False, "Planner failed to retain active ExecutionPlan in scratchpad."

        # Verification Invariant 1: Non-empty tasks
        if plan.total_tasks == 0:
            return False, "Generated execution plan contains zero tasks."

        # Verification Invariant 2: Acyclicity via Kahn's algorithm
        try:
            topo = plan.dag.topological_sort()
            if len(topo) != plan.total_tasks:
                return False, f"Topological sort count {len(topo)} does not match total tasks {plan.total_tasks}."
        except CyclicDependencyError as c_err:
            return False, f"Cyclic dependency detected in execution graph: {c_err}"

        # Verification Invariant 3: Dependency resolution integrity
        for t_id, planned_task in plan.tasks.items():
            for dep_id in planned_task.dependencies:
                if dep_id not in plan.tasks:
                    return False, f"Task '{t_id}' references non-existent prerequisite dependency '{dep_id}'."

        # Verification Invariant 4: Terminal synthesis node exists
        leaf_nodes = plan.dag.get_leaf_tasks()
        has_synthesizer = any(plan.tasks[leaf_id].agent_role == "synthesizer" for leaf_id in leaf_nodes)
        if not has_synthesizer:
            return False, "Plan lacks a terminal synthesizer leaf task to aggregate multi-agent findings."

        return (
            True,
            (
                f"Plan verified successfully: {plan.total_tasks} tasks scheduled across "
                f"{plan.total_stages} parallel stages (Complexity: {plan.complexity.value})."
            ),
        )
